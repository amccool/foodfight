// A 5x7 arcade-style pixel font rendered from the white pixel texture.
// Replaces SpriteFont so the port needs no content pipeline (which also
// keeps the UWP/Xbox build dead simple). Text is uppercased on draw.

using System.Collections.Generic;
using Microsoft.Xna.Framework;
