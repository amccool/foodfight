    public class PixelFont
    {
        private readonly Texture2D _pixel;

        public PixelFont(Texture2D pixel) { _pixel = pixel; }

        /// <summary>Advance per character in unscaled pixels (5 + 1 gap).</summary>
        public const int Advance = 6;
        public const int GlyphH = 7;

        public int Measure(string text, int scale)
        {
            if (string.IsNullOrEmpty(text)) return 0;
            return (text.Length * Advance - 1) * scale;
        }

        public void Draw(SpriteBatch sb, string text, float x, float y,
                         int scale, Color col)
        {
            text = text.ToUpperInvariant();
            float cx = x;
            foreach (char ch in text)
            {
                string[] rows;
                if (Glyphs.TryGetValue(ch, out rows))
                {
                    for (int r = 0; r < rows.Length; r++)
                    {
                        string row = rows[r];
                        for (int c = 0; c < row.Length; c++)
                        {
                            if (row[c] == '1')
                            {
                                sb.Draw(_pixel, new Rectangle(
                                    (int)(cx + c * scale), (int)(y + r * scale),
                                    scale, scale), col);
                            }
                        }
                    }
                }
                cx += Advance * scale;
            }
        }

